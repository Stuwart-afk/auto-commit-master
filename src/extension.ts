
import * as path from 'path';
import * as vscode from 'vscode';

import { getFiles } from './helpers/getListOfFiles';
import { runGit } from './helpers/runGit';
import { checkGitStatus } from './helpers/checkGitStatus';
import { findGitFolders, GitFolder } from './helpers/checkGitFolders';
import { commitSingleFile, findRepoRoot } from './helpers/commitSingleFile';

import {
   selectCopilotModel,
   generateCopilotCommitMessage,
} from './helpers/generateCopilotCommitMessage';

import {
   error as logError,
   initLogger,
   isVerbose,
   log,
   setVerbose,
   show as showLogs,
   warn as logWarn,
} from './helpers/logger';

let stopFlag = false;

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/**
 * Process every changed file inside a repository.
 * Each file receives its own Conventional Commit message generated by Copilot.
 */
const addGitCommits = async (
   repoPath: string,
   model: vscode.LanguageModelChat
): Promise<void> => {
   log('addGitCommits: start', repoPath);

   const files = await getFiles(repoPath);
   const { newFiles, modifiedFiles, deletedFiles } = files;

   log('addGitCommits: bucket sizes', {
      repoPath,
      new: newFiles.length,
      modified: modifiedFiles.length,
      deleted: deletedFiles.length,
   });

   // Process deleted files first
   for (const file of deletedFiles) {
      if (stopFlag) return;

      await runGit(['rm', '--', file], { cwd: repoPath });

      const message = await generateCopilotCommitMessage(
         repoPath,
         file,
         'Delete',
         model
      );

      log('addGitCommits: deleting', { repoPath, file, message });

      await runGit(['commit', '-m', message], { cwd: repoPath });
   }

   // Process modified files second
   for (const file of modifiedFiles) {
      if (stopFlag) return;

      await runGit(['add', '--', file], { cwd: repoPath });

      const message = await generateCopilotCommitMessage(
         repoPath,
         file,
         'Update',
         model
      );

      log('addGitCommits: updating', { repoPath, file, message });

      await runGit(['commit', '-m', message], { cwd: repoPath });
   }

   // Process new files last
   for (const file of newFiles) {
      if (stopFlag) return;

      await runGit(['add', '--', file], { cwd: repoPath });

      const message = await generateCopilotCommitMessage(
         repoPath,
         file,
         'Add',
         model
      );

      log('addGitCommits: adding', { repoPath, file, message });

      await runGit(['commit', '-m', message], { cwd: repoPath });
   }

   log('addGitCommits: done', repoPath);
};

/** Collect every Git repository reachable from open workspace folders. */
const collectGitFolders = async (): Promise<GitFolder[]> => {
   const folders = vscode.workspace.workspaceFolders;

   log('collectGitFolders: workspaceFolders', folders?.length ?? 0);

   if (!folders || folders.length === 0) {
      logWarn('collectGitFolders: no workspace folders open');
      return [];
   }

   const found: GitFolder[] = [];

   for (const folder of folders) {
      log('collectGitFolders: workspace folder', folder.uri.fsPath, folder.name);

      const result = await findGitFolders(folder.uri.fsPath);
      found.push(...result);
   }

   const seen = new Set<string>();
   const unique: GitFolder[] = [];

   for (const gitFolder of found) {
      if (seen.has(gitFolder.path)) continue;

      seen.add(gitFolder.path);
      unique.push(gitFolder);
   }

   log('collectGitFolders: unique repos', unique.map((g) => `${g.name}@${g.path}`));

   return unique;
};

export function activate(context: vscode.ExtensionContext) {
   // Logger setup
   const outputChannel = vscode.window.createOutputChannel('Auto Commit Master');

   context.subscriptions.push(outputChannel);

   const verbose = vscode.workspace
      .getConfiguration()
      .get<boolean>('autoCommitMaster.verbose', false);

   initLogger(outputChannel, { verbose });

   log('activate: extension activated', {
      version: context.extension.packageJSON.version,
      extensionPath: context.extension.extensionPath,
      verbose,
   });

   // React to configuration changes
   context.subscriptions.push(
      vscode.workspace.onDidChangeConfiguration((e) => {
         if (e.affectsConfiguration('autoCommitMaster.verbose')) {
            const next = vscode.workspace
               .getConfiguration()
               .get<boolean>('autoCommitMaster.verbose', false);

            setVerbose(!!next);
         }
      })
   );

   const setActive = (active: boolean) =>
      vscode.commands.executeCommand('setContext', 'autoCommitMaster.active', active);

   // Bulk commit command
   const start = vscode.commands.registerCommand(
      'auto-commit-master.start',
      async (...args: unknown[]) => {
         log('start: command invoked');

         if (isVerbose()) showLogs(true);

         const sourceControl = args.find(
            (a): a is vscode.SourceControl =>
               !!a &&
               typeof a === 'object' &&
               'rootUri' in (a as object) &&
               'id' in (a as object)
         );

         let targets: GitFolder[] = [];

         if (sourceControl?.rootUri) {
            const repoPath = sourceControl.rootUri.fsPath;

            targets = [{
               path: repoPath,
               name: path.basename(repoPath) || repoPath,
            }];
         } else {
            const gitFolders = await collectGitFolders();

            if (gitFolders.length === 0) {
               vscode.window.showErrorMessage(
                  'No Git repositories found in the workspace'
               );

               setActive(false);
               return;
            }

            if (gitFolders.length === 1) {
               targets = gitFolders;
            } else {
               const activeFilePath =
                  vscode.window.activeTextEditor?.document.uri.fsPath;

               const activeRepo = activeFilePath
                  ? gitFolders.find(
                       (c) =>
                          activeFilePath === c.path ||
                          activeFilePath.startsWith(c.path + path.sep)
                    )
                  : undefined;

               if (activeRepo) {
                  targets = [activeRepo];
               } else {
                  vscode.window.showErrorMessage(
                     `Multiple repositories found: ${gitFolders
                        .map((g) => g.name)
                        .join(', ')}. Open a file inside the target repository or click its Auto Commit button.`
                  );

                  setActive(false);
                  return;
               }
            }
         }

         stopFlag = false;
         setActive(true);

         vscode.window.showInformationMessage(
            `Auto Commit Master started — ${targets[0].name}!`
         );

         let hasErrors = false;

         // Reuse one Copilot model across all repositories.
         let model: vscode.LanguageModelChat | undefined;

         const totalRepos = targets.length;

         for (let i = 0; i < targets.length; i++) {
            if (stopFlag) break;

            const gitFolder = targets[i];

            const label =
               totalRepos > 1
                  ? `${gitFolder.name} (${i + 1}/${totalRepos})`
                  : gitFolder.name;

            await vscode.window.withProgress(
               {
                  location: vscode.ProgressLocation.Notification,
                  title: `Auto Commit Master — ${label}`,
                  cancellable: false,
               },
               async () => {
                  try {
                     const status = await checkGitStatus(gitFolder.path);

                     if (status.error) {
                        hasErrors = true;

                        vscode.window.showErrorMessage(
                           `Error in ${gitFolder.name}: ${status.error}`
                        );

                        return;
                     }

                     if (status.clean) {
                        log('start: repo is clean, skipping', gitFolder.name);
                        return;
                     }

                     if (stopFlag) return;

                     // Select Copilot only when there are actual changes.
                     if (!model) {
                        model = await selectCopilotModel();
                     }

                     await addGitCommits(gitFolder.path, model);
                  } catch (error: any) {
                     hasErrors = true;

                     logError('start: error processing repo', {
                        repo: gitFolder.name,
                        error,
                     });

                     vscode.window.showErrorMessage(
                        `Error processing ${gitFolder.name}: ${
                           error?.message ?? String(error)
                        }`
                     );
                  }
               }
            );
         }

         if (!stopFlag) {
            setActive(false);

            if (!hasErrors) {
               await sleep(150);

               vscode.window.showInformationMessage(
                  `Files committed in ${targets[0].name}.`
               );
            }
         } else {
            logWarn('start: finished after stop');
         }
      }
   );

   // Stop command
   const stop = vscode.commands.registerCommand(
      'auto-commit-master.stop',
      () => {
         log('stop: command invoked', { stopFlagBefore: stopFlag });

         stopFlag = true;
         setActive(false);

         vscode.window.showInformationMessage(
            'Auto Commit Master stopped!'
         );
      }
   );

   // Single-file commit helpers
   type ScmResourceStateLike = {
      resourceUri: vscode.Uri;
   };

   const isUriLike = (a: unknown): a is vscode.Uri =>
      a instanceof vscode.Uri ||
      (!!a &&
         typeof a === 'object' &&
         typeof (a as { fsPath?: unknown }).fsPath === 'string');

   const hasResourceUri = (a: unknown): a is ScmResourceStateLike =>
      !!a &&
      typeof a === 'object' &&
      'resourceUri' in (a as object) &&
      isUriLike((a as { resourceUri: unknown }).resourceUri);

   const collectUrisFromArgs = (args: unknown[]): vscode.Uri[] => {
      const out: vscode.Uri[] = [];

      const visit = (value: unknown): void => {
         if (value === null || value === undefined) return;

         if (value instanceof vscode.Uri) {
            out.push(value);
            return;
         }

         if (hasResourceUri(value)) {
            out.push(value.resourceUri);
            return;
         }

         if (Array.isArray(value)) {
            for (const item of value) visit(item);
         }
      };

      for (const arg of args) visit(arg);

      return out;
   };

   // Individual file commit command
   const commitFile = vscode.commands.registerCommand(
      'auto-commit-master.commitFile',
      async (...args: unknown[]) => {
         log('commitFile: command invoked', {
            argCount: args.length,
         });

         if (isVerbose()) showLogs(true);

         const targets = collectUrisFromArgs(args);

         if (targets.length === 0) {
            vscode.window.showInformationMessage(
               'Select a file in the SCM view to commit.'
            );

            return;
         }

         stopFlag = false;

         let committedCount = 0;
         let skippedCount = 0;

         const skipped: string[] = [];

         for (const fileUri of targets) {
            if (stopFlag) break;

            const filePath = fileUri.fsPath;
            const repoPath = findRepoRoot(filePath);

            if (!repoPath) {
               skipped.push(
                  `${path.basename(filePath)} (not in a Git repository)`
               );

               skippedCount++;
               continue;
            }

            const relativePath = path.relative(repoPath, filePath);

            try {
               // Generate a Copilot-powered Conventional Commit for this file.
               const result = await commitSingleFile({
                  repoPath,
                  relativePath,
                  shouldStop: () => stopFlag,
               });

               log('commitFile: result', {
                  filePath,
                  result,
               });

               if (result.committed) {
                  committedCount++;
               } else if (result.reason === 'no-changes') {
                  skipped.push(
                     `${path.basename(filePath)} (no changes)`
                  );

                  skippedCount++;
               }
            } catch (error: any) {
               logError('commitFile: failed', {
                  filePath,
                  repoPath,
                  error,
               });

               vscode.window.showErrorMessage(
                  `Failed to commit ${path.basename(filePath)}: ${
                     error?.message ?? String(error)
                  }`
               );
            }
         }

         if (targets.length === 1) {
            if (committedCount === 1) {
               vscode.window.showInformationMessage('File committed.');
            } else if (skippedCount === 1) {
               vscode.window.showInformationMessage(skipped[0]);
            }
         } else if (committedCount > 0) {
            const skipSuffix =
               skippedCount > 0 ? `, ${skippedCount} skipped` : '';

            vscode.window.showInformationMessage(
               `Committed ${committedCount} file${
                  committedCount === 1 ? '' : 's'
               }${skipSuffix}.`
            );
         } else if (skippedCount > 0) {
            vscode.window.showInformationMessage(
               skipped.join('; ')
            );
         }
      }
   );

   // Show logs command
   const showLogsCommand = vscode.commands.registerCommand(
      'auto-commit-master.showLogs',
      () => {
         log('showLogs: command invoked');
         showLogs(false);
      }
   );

   context.subscriptions.push(
      start,
      stop,
      commitFile,
      showLogsCommand
   );

   setActive(false);

   log('activate: ready');
}

export function deactivate() {
   log('deactivate: extension deactivating');
}
